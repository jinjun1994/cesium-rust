//! TileMapServiceImageryProvider matching CesiumJS `Scene/TileMapServiceImageryProvider.js` (Apache-2.0).

use cesium_math::{
    Cartographic, DeveloperError, Ellipsoid, GeoRectangle, GeographicTilingScheme,
    RuntimeError, WebMercatorTilingScheme,
};

use crate::imagery_layer::ImageryProvider;
use crate::quadtree_tile::AnyTilingScheme;

/// Initialization options for `TileMapServiceImageryProvider`.
#[derive(Clone, Debug, Default)]
pub struct TileMapServiceImageryProviderOptions {
    pub url: Option<String>,
    pub file_extension: Option<String>,
    pub credit: Option<String>,
    pub minimum_level: Option<u32>,
    pub maximum_level: Option<u32>,
    pub rectangle: Option<GeoRectangle>,
    pub tiling_scheme: Option<AnyTilingScheme>,
    pub ellipsoid: Option<Ellipsoid>,
    pub tile_width: Option<u32>,
    pub tile_height: Option<u32>,
    pub flip_xy: Option<bool>,
}

/// An imagery provider that provides tiled imagery as generated by MapTiler / GDAL2Tiles / TMS.
#[derive(Clone, Debug)]
pub struct TileMapServiceImageryProvider {
    url: String,
    url_template: String,
    file_extension: String,
    tile_width: u32,
    tile_height: u32,
    minimum_level: u32,
    maximum_level: Option<u32>,
    tiling_scheme: AnyTilingScheme,
    rectangle: GeoRectangle,
    credit: Option<String>,
    has_alpha_channel: bool,
}

impl TileMapServiceImageryProvider {
    /// Creates a `TileMapServiceImageryProvider` from a URL string with default fallback metadata.
    pub fn from_url(
        url: &str,
        options: Option<TileMapServiceImageryProviderOptions>,
    ) -> Result<Self, DeveloperError> {
        if url.trim().is_empty() {
            return Err(DeveloperError::new("url is required."));
        }

        let opts = options.unwrap_or_default();
        let mut clean_url = url.trim_end_matches('/').to_string();
        clean_url.push('/');

        let file_extension = opts.file_extension.unwrap_or_else(|| "png".to_string());
        let tile_width = opts.tile_width.unwrap_or(256);
        let tile_height = opts.tile_height.unwrap_or(256);
        let ellipsoid = opts.ellipsoid.unwrap_or(Ellipsoid::WGS84);

        let tiling_scheme = opts.tiling_scheme.unwrap_or_else(|| {
            let wm = WebMercatorTilingScheme::new(ellipsoid, None, 1, 1)
                .unwrap_or_else(|_| WebMercatorTilingScheme::default());
            AnyTilingScheme::WebMercator(wm)
        });

        let mut rectangle = opts.rectangle.unwrap_or_else(|| tiling_scheme.rectangle());
        confine_rectangle_to_tiling_scheme(&mut rectangle, &tiling_scheme);

        let minimum_level = opts.minimum_level.unwrap_or(0);
        let maximum_level = opts.maximum_level;

        let url_template = format!("{clean_url}{{z}}/{{x}}/{{reverseY}}.{file_extension}");

        Ok(Self {
            url: clean_url,
            url_template,
            file_extension,
            tile_width,
            tile_height,
            minimum_level,
            maximum_level,
            tiling_scheme,
            rectangle,
            credit: opts.credit,
            has_alpha_channel: true,
        })
    }

    /// Parses TMS `tilemapresource.xml` content and constructs the imagery provider.
    pub fn from_xml(
        xml: &str,
        url: &str,
        options: Option<TileMapServiceImageryProviderOptions>,
    ) -> Result<Self, RuntimeError> {
        if url.trim().is_empty() {
            return Err(RuntimeError::new("url is required."));
        }

        let mut clean_url = url.trim_end_matches('/').to_string();
        clean_url.push('/');
        let xml_url = format!("{clean_url}tilemapresource.xml");

        let opts = options.unwrap_or_default();

        // Check for BoundingBox
        let bbox_tag = find_tag(xml, "BoundingBox").or_else(|| find_tag(xml, "boundingbox"));
        let tilesets_tag = find_tag(xml, "TileSets").or_else(|| find_tag(xml, "tilesets"));

        if bbox_tag.is_none() || tilesets_tag.is_none() {
            return Err(RuntimeError::new(format!(
                "Unable to find expected tilesets or bbox attributes in {xml_url}."
            )));
        }

        let tilesets_str = tilesets_tag.unwrap();
        let profile = extract_attr(tilesets_str, "profile").unwrap_or_default();

        let ellipsoid = opts.ellipsoid.unwrap_or(Ellipsoid::WGS84);
        let tiling_scheme = if let Some(ts) = opts.tiling_scheme {
            ts
        } else {
            match profile.as_str() {
                "geodetic" | "global-geodetic" => {
                    let geo = GeographicTilingScheme::new(ellipsoid, GeoRectangle::MAXIMUM, 2, 1)
                        .unwrap_or_else(|_| GeographicTilingScheme::default());
                    AnyTilingScheme::Geographic(geo)
                }
                "mercator" | "global-mercator" => {
                    let wm = WebMercatorTilingScheme::new(ellipsoid, None, 1, 1)
                        .unwrap_or_else(|_| WebMercatorTilingScheme::default());
                    AnyTilingScheme::WebMercator(wm)
                }
                _ => {
                    return Err(RuntimeError::new(format!(
                        "{xml_url} specifies an unsupported profile attribute, {profile}."
                    )));
                }
            }
        };

        // Format
        let format_tag = find_tag(xml, "TileFormat").or_else(|| find_tag(xml, "tileformat"));
        let ext_from_xml = format_tag.and_then(|f| extract_attr(f, "extension"));
        let width_from_xml = format_tag
            .and_then(|f| extract_attr(f, "width"))
            .and_then(|w| w.parse::<u32>().ok());
        let height_from_xml = format_tag
            .and_then(|f| extract_attr(f, "height"))
            .and_then(|h| h.parse::<u32>().ok());

        let file_extension = opts
            .file_extension
            .or(ext_from_xml)
            .unwrap_or_else(|| "png".to_string());
        let tile_width = opts.tile_width.or(width_from_xml).unwrap_or(256);
        let tile_height = opts.tile_height.or(height_from_xml).unwrap_or(256);

        // Orders from TileSet
        let orders = extract_tileset_orders(xml);
        let parsed_min = orders.first().copied();
        let parsed_max = orders.last().copied();

        let minimum_level = opts.minimum_level.or(parsed_min).unwrap_or(0);
        let maximum_level = opts.maximum_level.or(parsed_max);

        // Rectangle
        let rectangle = if let Some(r) = opts.rectangle {
            r
        } else {
            let bbox_str = bbox_tag.unwrap();
            let minx = extract_attr(bbox_str, "minx")
                .and_then(|v| v.parse::<f64>().ok())
                .unwrap_or(-180.0);
            let miny = extract_attr(bbox_str, "miny")
                .and_then(|v| v.parse::<f64>().ok())
                .unwrap_or(-90.0);
            let maxx = extract_attr(bbox_str, "maxx")
                .and_then(|v| v.parse::<f64>().ok())
                .unwrap_or(180.0);
            let maxy = extract_attr(bbox_str, "maxy")
                .and_then(|v| v.parse::<f64>().ok())
                .unwrap_or(90.0);

            let (sw_lon, sw_lat, ne_lon, ne_lat) = if opts.flip_xy.unwrap_or(false) {
                (miny, minx, maxy, maxx)
            } else {
                (minx, miny, maxx, maxy)
            };

            let sw = Cartographic::from_degrees(sw_lon, sw_lat, None);
            let ne = Cartographic::from_degrees(ne_lon, ne_lat, None);
            let mut r = GeoRectangle::new(sw.longitude, sw.latitude, ne.longitude, ne.latitude);
            confine_rectangle_to_tiling_scheme(&mut r, &tiling_scheme);
            r
        };

        let url_template = format!("{clean_url}{{z}}/{{x}}/{{reverseY}}.{file_extension}");

        Ok(Self {
            url: clean_url,
            url_template,
            file_extension,
            tile_width,
            tile_height,
            minimum_level,
            maximum_level,
            tiling_scheme,
            rectangle,
            credit: opts.credit,
            has_alpha_channel: true,
        })
    }

    pub fn url(&self) -> &str {
        &self.url
    }

    pub fn url_template(&self) -> &str {
        &self.url_template
    }

    pub fn file_extension(&self) -> &str {
        &self.file_extension
    }

    pub fn tile_width(&self) -> u32 {
        self.tile_width
    }

    pub fn tile_height(&self) -> u32 {
        self.tile_height
    }

    pub fn minimum_level(&self) -> u32 {
        self.minimum_level
    }

    pub fn maximum_level(&self) -> Option<u32> {
        self.maximum_level
    }

    pub fn tiling_scheme(&self) -> &AnyTilingScheme {
        &self.tiling_scheme
    }

    pub fn rectangle(&self) -> GeoRectangle {
        self.rectangle
    }

    pub fn credit(&self) -> Option<&str> {
        self.credit.as_deref()
    }

    pub fn has_alpha_channel(&self) -> bool {
        self.has_alpha_channel
    }

    /// Computes the tile URL for a given (x, y, level) coordinate.
    pub fn tile_url(&self, x: u32, y: u32, level: u32) -> String {
        let total_y = self.tiling_scheme.number_of_y_tiles_at_level(level);
        let reverse_y = total_y.saturating_sub(1).saturating_sub(y);
        format!(
            "{}{}/{}/{}.{}",
            self.url, level, x, reverse_y, self.file_extension
        )
    }
}

impl ImageryProvider for TileMapServiceImageryProvider {
    fn rectangle(&self) -> GeoRectangle {
        self.rectangle
    }

    fn tile_width(&self) -> u32 {
        self.tile_width
    }

    fn tile_height(&self) -> u32 {
        self.tile_height
    }

    fn minimum_level(&self) -> u32 {
        self.minimum_level
    }

    fn maximum_level(&self) -> Option<u32> {
        self.maximum_level
    }

    fn has_alpha_channel(&self) -> bool {
        self.has_alpha_channel
    }

    fn ellipsoid(&self) -> Ellipsoid {
        self.tiling_scheme.ellipsoid()
    }
}

fn confine_rectangle_to_tiling_scheme(rectangle: &mut GeoRectangle, tiling_scheme: &AnyTilingScheme) {
    let scheme_rect = tiling_scheme.rectangle();
    if rectangle.west < scheme_rect.west {
        rectangle.west = scheme_rect.west;
    }
    if rectangle.east > scheme_rect.east {
        rectangle.east = scheme_rect.east;
    }
    if rectangle.south < scheme_rect.south {
        rectangle.south = scheme_rect.south;
    }
    if rectangle.north > scheme_rect.north {
        rectangle.north = scheme_rect.north;
    }
}

fn find_tag<'a>(xml: &'a str, tag_name: &str) -> Option<&'a str> {
    let start_needle = format!("<{tag_name}");
    let start_pos = xml.find(&start_needle)?;
    let sub = &xml[start_pos..];
    let end_pos = sub.find('>')?;
    Some(&sub[..=end_pos])
}

fn extract_attr(tag_str: &str, attr_name: &str) -> Option<String> {
    let pattern = format!("{attr_name}=\"");
    let start = tag_str.find(&pattern)? + pattern.len();
    let rest = &tag_str[start..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

fn extract_tileset_orders(xml: &str) -> Vec<u32> {
    let mut orders = Vec::new();
    let mut cursor = xml;
    while let Some(pos) = cursor.find("<TileSet") {
        let tag_part = &cursor[pos..];
        if let Some(end) = tag_part.find('>') {
            let full_tag = &tag_part[..=end];
            if let Some(order_str) = extract_attr(full_tag, "order") {
                if let Ok(order) = order_str.parse::<u32>() {
                    orders.push(order);
                }
            }
            cursor = &tag_part[end + 1..];
        } else {
            break;
        }
    }
    orders.sort_unstable();
    orders
}
